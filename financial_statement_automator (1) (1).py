        # 1. Gather all inputs from the UI
        entity_name = self.entity_name_entry.get()
        assessment_year = self.assessment_year_entry.get()
        financial_year = self.financial_year_entry.get()
        entity_type = self.entity_type_var.get()
        formatting_option = self.formatting_option_var.get()
        prior_year_data_available = self.prior_year_data_available_var.get()
        current_year_source = self.current_year_source_var.get()

        self.log_message(f"Entity: {entity_name}, Type: {entity_type}, FY: {financial_year}, AY: {assessment_year}")
        self.log_message(f"Formatting Option: {formatting_option}")
        self.log_message(f"Prior Year Data Available: {prior_year_data_available}")
        self.log_message(f"Current Year Data Source: {current_year_source}")

        # 2. Implement Formatting Logic (Step 2)
        self.progress_bar.set(0.1)
        self.log_message("Processing formatting master...")
        template_df = pd.DataFrame() # Initialize an empty DataFrame

        if formatting_option == "standard":
            self.log_message("Using standard ICAI / Schedule III template.")
            template_df = self._load_standard_template(entity_type)
            self.log_message(f"Standard template loaded with {len(template_df)} rows and {len(template_df.columns)} columns.")
        elif formatting_option == "custom":
            custom_file = self.file_paths["custom_formatting_file"]
            if custom_file and os.path.exists(custom_file):
                self.log_message(f"Cloning layout from custom file: {os.path.basename(custom_file)}")
                try:
                    template_df = pd.read_excel(custom_file)
                    self.log_message(f"Custom template loaded from {os.path.basename(custom_file)} with {len(template_df)} rows and {len(template_df.columns)} columns.")
                except Exception as e:
                    self.log_message(f"Error loading custom formatting file: {e}")
                    messagebox.showerror("File Error", f"Could not load custom formatting file: {e}")
                    return # Stop generation on error
            else:
                self.log_message("No valid custom formatting file selected. Using a basic placeholder template.")
                template_df = pd.DataFrame({'Note': ['No custom file provided, using basic placeholder.']})
        self.update_idletasks()

        # 3. Process Prior Year Figures (Step 3)
        self.progress_bar.set(0.25)
        self.log_message("Processing prior year figures...")
        prior_year_data = {} # Placeholder for prior year financial data
        if prior_year_data_available:
            prior_year_file = self.file_paths["prior_year_financials_file"]
            if prior_year_file and os.path.exists(prior_year_file):
                prior_year_data = self._process_prior_year_financials(prior_year_file)
                self.log_message(f"Prior year data processed. Keys: {list(prior_year_data.keys())}")
            else:
                self.log_message("Prior year data toggled ON, but no valid file selected or file does not exist.")
        else:
            self.log_message("Prior year data not available/toggled OFF.")
        self.update_idletasks()

        # 4. Process Current Year Data Ingestion (Step 4)
        self.progress_bar.set(0.4)
        self.log_message("Processing current year data...")
        current_year_data = {} # Placeholder for current year financial data
        if current_year_source == "trial_balance":
            tb_file = self.file_paths["current_year_trial_balance_file"]
            if tb_file and os.path.exists(tb_file):
                current_year_data['trial_balance'] = self._process_trial_balance_data(tb_file)
                if not current_year_data['trial_balance'].empty:
                    self.log_message("Trial Balance data successfully loaded into current_year_data.")
            else:
                self.log_message("No valid Trial Balance file selected or file does not exist.")
        elif current_year_source == "draft_bs_pl":
            draft_file = self.file_paths["current_year_draft_bs_pl_file"]
            if draft_file and os.path.exists(draft_file):
                current_year_data['draft_bs_pl'] = self._process_draft_bs_pl_data(draft_file)
                if current_year_data['draft_bs_pl']:
                    self.log_message("Draft Balance Sheet & P&L data successfully loaded into current_year_data.")
            else:
                self.log_message("No valid Draft Balance Sheet & P&L file selected or file does not exist.")
        elif current_year_source == "tally_prime":
            self.log_message("Attempting to fetch data directly from Tally Prime (simulated).")
            # Logic for Tally Prime integration (needs a separate service/API call)
            current_year_data['tally_data'] = {'status': 'Tally Prime data fetch simulated'}
            self.log_message("Simulated Tally Prime data fetch completed.")
        # Other accounting software (SAP/Oracle) would extend this logic
        self.update_idletasks()

        # 5. Process Depreciation Engine Options (Step 5)
        self.progress_bar.set(0.6)
        self.log_message("Calculating depreciation...")
        depreciation_data = {} # Placeholder for depreciation calculation results
        if entity_type in ["Proprietorship", "Partnership Firm", "Trust"]:
            self.log_message("Entity is Non-Corporate. Calculating depreciation as per Income Tax Act 1961.")
            it_block_file = self.file_paths["income_tax_block_register_file"]
            if it_block_file and os.path.exists(it_block_file):
                depreciation_data['it_depreciation'] = self._calculate_it_depreciation_non_corporate(it_block_file)
                self.log_message(f"Non-corporate IT depreciation calculated: {depreciation_data['it_depreciation']}")
            else:
                self.log_message("Income Tax Block Register not provided for non-corporate entity or file does not exist. Skipping IT depreciation calculation.")
        elif entity_type == "Private Limited / Limited Company":
            self.log_message("Entity is a Company. Calculating dual depreciation (Companies Act & Income Tax Act).")
            schedule_ii_file = self.file_paths["schedule_ii_asset_register_file"]
            it_wdv_file = self.file_paths["income_tax_wdv_schedule_file"]

            if schedule_ii_file and os.path.exists(schedule_ii_file):
                depreciation_data['co_depreciation'] = self._calculate_companies_act_depreciation(schedule_ii_file)
                self.log_message(f"Companies Act depreciation calculated: {depreciation_data['co_depreciation']}")
            else:
                self.log_message("Schedule II Asset Register not provided for company or file does not exist. Skipping Companies Act depreciation calculation.")

            if it_wdv_file and os.path.exists(it_wdv_file):
                depreciation_data['it_depreciation_company'] = self._calculate_it_depreciation_company(it_wdv_file)
                self.log_message(f"Company IT WDV depreciation calculated: {depreciation_data['it_depreciation_company']}")
            else:
                self.log_message("Income Tax WDV Schedule not provided for company or file does not exist. Skipping Company IT WDV depreciation calculation.")

            if not (schedule_ii_file and it_wdv_file and os.path.exists(schedule_ii_file) and os.path.exists(it_wdv_file)):
                self.log_message("Both Schedule II Asset Register and Income Tax WDV Schedule are recommended for companies for dual depreciation calculation. Please provide both for complete results.")

        self.update_idletasks()

        # 6. Generate the Financial Statements (Integration and Output)
        self.progress_bar.set(0.8)
        self.log_message("Integrating data and generating final Excel report...")
        output_filename = f"Financial_Statements_{entity_name}_{financial_year}.xlsx"

        # Call the new helper method to write to Excel
        if self._write_financial_statements_to_excel(output_filename, template_df, prior_year_data, current_year_data, depreciation_data):
            self.progress_bar.set(1.0)
            self.log_message(f"Financial statements generated successfully (simulated) as {output_filename}!")
            messagebox.showinfo("Generation Complete", f"Financial statements have been generated as {output_filename}.")
        else:
            self.log_message("Financial statement generation failed.")
            messagebox.showerror("Generation Failed", "Failed to generate financial statements.")

        self.update_idletasks()


