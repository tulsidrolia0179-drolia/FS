    def select_file(self, label_widget, file_types, file_key):
        filetypes_list = []
        for ft in file_types.split():
            filetypes_list.append((f"*{ft} files", f"*{ft}"))
        filetypes_list.append(("All files", "*.* "))

        filepath = filedialog.askopenfilename(filetypes=filetypes_list)
        if filepath:
            label_widget.configure(text=os.path.basename(filepath))
            self.file_paths[file_key] = filepath # Store the full path
            self.log_message(f"Selected file for {file_key}: {os.path.basename(filepath)}")
        else:
            label_widget.configure(text="No file selected")
            self.file_paths[file_key] = None # Clear the path if selection is cancelled
            self.log_message(f"File selection cancelled for {file_key}.")

